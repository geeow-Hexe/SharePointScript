$Global:SPConfig = @{

    # ----------------------------------------------------------------------
    # 必須
    # ----------------------------------------------------------------------
    # Entra ID (Azure AD) に登録したアプリの「アプリケーション (クライアント) ID」
    #   未登録の場合は README の「アプリ登録」を参照
    AppId      = "00000000-0000-0000-0000-000000000000"

    # 既定の操作対象サイト URL  (各スクリプトの -SiteUrl で個別に上書き可能)
    SiteUrl    = "https://contoso.sharepoint.com/sites/sample"

    # テナント名  (https://xxx.sharepoint.com の xxx 部分)
    TenantName = "contoso"

    # ----------------------------------------------------------------------
    # 認証方式
    # ----------------------------------------------------------------------
    #   Interactive : ブラウザでサインイン (通常はこれ)
    #   DeviceLogin : デバイスコードでサインイン (ブラウザが開けない環境向け)
    #   Certificate : 証明書ファイル (.pfx) によるアプリ専用認証 (無人実行向け)
    #   Thumbprint  : 証明書ストア内の証明書 (拇印指定) によるアプリ専用認証
    AuthMode              = "Interactive"
    CertificatePath       = ""      # AuthMode = Certificate の場合: .pfx のパス
    CertificatePassword   = ""      # AuthMode = Certificate の場合: .pfx のパスワード (不要なら空)
    CertificateThumbprint = ""      # AuthMode = Thumbprint  の場合: 証明書の拇印

    # ----------------------------------------------------------------------
    # サイト作成時の既定値
    # ----------------------------------------------------------------------
    Lcid       = 1041   # 1041 = 日本語
    TimeZoneId = 20     # 20   = (UTC+09:00) 大阪、札幌、東京

    # ----------------------------------------------------------------------
    # 権限レベルの表示名 (サイトの言語に合わせて変更)
    #   英語サイトの場合: "Full Control", "Design", "Edit", "Contribute", "Read"
    # ----------------------------------------------------------------------
    RoleNames = @{
        FullControl = "フル コントロール"
        Design      = "デザイン"
        Edit        = "編集"
        Contribute  = "投稿"
        Read        = "閲覧"
    }

    # ----------------------------------------------------------------------
    # 任意 (空欄の場合は自動設定)
    # ----------------------------------------------------------------------
    AdminUrl  = ""   # 空なら https://<TenantName>-admin.sharepoint.com
    Tenant    = ""   # 空なら <TenantName>.onmicrosoft.com
    OutputDir = ""   # レポート等の出力先。空なら <リポジトリ>\Output
}
