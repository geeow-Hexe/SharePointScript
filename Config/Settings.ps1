    共通設定ファイル  ※ 環境に合わせて編集するのは基本的にこのファイルだけです
    ==========================================================================

    ・全スクリプトは Common\Common.ps1 経由でこの $SPConfig を参照します。
    ・個人環境用に一部だけ上書きしたい場合は、同じフォルダに Settings.local.ps1 を作成し
      必要なキーだけ  $SPConfig.AppId = "..."  のように記述してください (Git 管理対象外)。
      → サンプル: Settings.local.sample.ps1
